    new_orig = txn.get("newbalanceOrig")
    old_dest = txn.get("oldbalanceDest")
    new_dest = txn.get("newbalanceDest")
    step_val = txn.get("step")
    is_flagged = txn.get("isFlaggedFraud")

    orig_delta_str = "Not available"
    if old_orig is not None and new_orig is not None:
        try:
            delta_orig = float(new_orig) - float(old_orig)
            pct_drain = (abs(delta_orig) / (float(old_orig) + 1e-6)) * 100 if float(old_orig) > 0 else 0.0
            orig_delta_str = f"{_format_currency(delta_orig)} ({pct_drain:.1f}% drain)"
        except Exception:
            orig_delta_str = "Not available"

    dest_delta_str = "Not available"
    if old_dest is not None and new_dest is not None:
        try:
            delta_dest = float(new_dest) - float(old_dest)
            if float(old_dest) == 0.0 and float(new_dest) == 0.0:
                dest_delta_str = "$0.00 (Zero-Balance Mule Pattern)"
            else:
                dest_delta_str = f"+{_format_currency(delta_dest)}"
        except Exception:
            dest_delta_str = "Not available"

    flag_str = "Yes" if is_flagged == 1 else "No"
    try:
        step_str = f"Step {step_val} (Hour {int(step_val) % 24})" if step_val is not None else "Not specified"
    except Exception:
        step_str = str(step_val)

    txn_matrix = [
        [
            Paragraph("<b>Transaction Type:</b>", styles["TableCellBold"]),
            Paragraph(f"<b>{_escape(txn_type)}</b>", styles["TableCell"]),
            Paragraph("<b>Transaction Amount:</b>", styles["TableCellBold"]),
            Paragraph(f'<font size="9"><b>{_format_currency(txn_amount)}</b></font>', styles["TableCell"])
        ],
        [
            Paragraph("<b>Sender Account (Origin):</b>", styles["TableCellBold"]),
            Paragraph(f'<font color="#1D4ED8"><b>{_escape(name_orig)}</b></font>', styles["TableCell"]),
            Paragraph("<b>Receiver Account (Dest):</b>", styles["TableCellBold"]),
            Paragraph(f'<font color="#B91C1C"><b>{_escape(name_dest)}</b></font>', styles["TableCell"])
        ],
        [
            Paragraph("<b>Sender Prior Balance:</b>", styles["TableCellBold"]),
            Paragraph(_format_currency(old_orig), styles["TableCell"]),
            Paragraph("<b>Receiver Prior Balance:</b>", styles["TableCellBold"]),
            Paragraph(_format_currency(old_dest), styles["TableCell"])
        ],
        [
            Paragraph("<b>Sender New Balance:</b>", styles["TableCellBold"]),
            Paragraph(_format_currency(new_orig), styles["TableCell"]),
            Paragraph("<b>Receiver New Balance:</b>", styles["TableCellBold"]),
            Paragraph(_format_currency(new_dest), styles["TableCell"])
        ],
        [
            Paragraph("<b>Sender Balance Delta:</b>", styles["TableCellBold"]),
            Paragraph(_escape(orig_delta_str), styles["TableCell"]),
            Paragraph("<b>Receiver Balance Delta:</b>", styles["TableCellBold"]),
            Paragraph(_escape(dest_delta_str), styles["TableCell"])
        ],
        [
            Paragraph("<b>Simulation / Step Hour:</b>", styles["TableCellBold"]),
            Paragraph(_escape(step_str), styles["TableCell"]),
            Paragraph("<b>System Flagged Rule:</b>", styles["TableCellBold"]),
            Paragraph(_escape(flag_str), styles["TableCell"])
        ]
    ]

    txn_table = Table(txn_matrix, colWidths=[115, 146, 115, 147])
    txn_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), HexColor("#FFFFFF")),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER_LIGHT),
        ('BACKGROUND', (0, 0), (0, -1), ROW_ALT_BG),
        ('BACKGROUND', (2, 0), (2, -1), ROW_ALT_BG),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    story.append(txn_table)
    story.append(Spacer(1, 8))

    # ── 3. RISK ANALYSIS & ML SIGNALS ─────────────────────────────────────────
    story.append(_create_section_heading("3. Risk Analysis & ML Signals", styles))
    story.append(Spacer(1, 4))

    score_val = fraud_score_data.get("risk_score", 0.0)
    score_pct_str = f"{score_val*100:.1f}%" if isinstance(score_val, (int, float)) else "0.0%"
    model_ver = fraud_score_data.get("model_version", "1.0")

    gauge_desc = (
        f"The <b>XGBoost ML Fraud Classifier (Model v{_escape(model_ver)})</b> evaluated this transaction "
        f"with a fraud probability score of <b>{score_pct_str}</b>, classifying it into the "
        f"<b><font color=\"{risk_text_color.hexval()}\">{_escape(risk_level)}</font></b> risk band. "
        f"Six behavioral, structural, and relational fraud signals were computed to assess anomaly severity:"
    )
    story.append(Paragraph(gauge_desc, styles["ReportBody"]))
    story.append(Spacer(1, 4))

    signals_fired = fraud_score_data.get("signals_fired") or {}

    def _assess_type(v):
        try:
            return "Triggered (High Risk)" if v is not None and float(v) > 0.5 else "Normal"
        except Exception:
            return "Evaluated"

    def _assess_ratio(v):
        try:
            if v is None: return "Normal"
            f = float(v)
            return f"High Drain ({f*100:.1f}%)" if f > 0.5 else f"Normal ({f*100:.1f}%)"
        except Exception:
            return "Evaluated"

    def _assess_mismatch(v):
        try:
            if v is None: return "Consistent"
            f = float(v)
            return f"Mismatch ({_format_currency(f)})" if abs(f) > 0.01 else "Consistent (0.00)"
        except Exception:
            return "Evaluated"

    def _assess_mule(v):
        try:
            return "Mule Signature Detected" if v is not None and float(v) > 0.5 else "Normal"
        except Exception:
            return "Evaluated"

    def _assess_timing(v):
        try:
            return f"Hour {int(float(v))}" if v is not None else "Normal"
        except Exception:
            return "Evaluated"

    def _assess_velocity(v):
        try:
            return f"Velocity: {_format_currency(v)}" if v is not None else "Standard"
        except Exception:
            return "Evaluated"

