        ("type_eligible", "Transaction Type Eligibility", "High-risk flow type (TRANSFER or CASH_OUT)", _assess_type),
        ("amount_balance_ratio", "Amount to Balance Ratio", "Ratio of transferred amount to sender's prior balance", _assess_ratio),
        ("balance_mismatch", "Balance Discrepancy", "Discrepancy between balance delta and transaction amount", _assess_mismatch),
        ("mule_pattern", "Zero-Balance Mule Signature", "Receiver starts and ends transaction with zero balance", _assess_mule),
