    for extra_key, extra_val in signals_fired.items():
        if extra_key not in [s[0] for s in signal_defs]:
            try:
                extra_raw = f"{float(extra_val):.4f}" if isinstance(extra_val, (int, float)) else str(extra_val)
            except Exception:
                extra_raw = str(extra_val)
            signals_rows.append([
                Paragraph(f"<b>{_escape(extra_key)}</b>", styles["TableCell"]),
                Paragraph(_escape(extra_raw), styles["TableCell"]),
                Paragraph("Custom computed feature signal", styles["TableCell"]),
                Paragraph("Evaluated", styles["TableCell"])
            ])

    signals_table = Table(signals_rows, colWidths=[125, 65, 215, 118])
