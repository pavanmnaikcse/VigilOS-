class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic total page count and professional headers/footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_decorations(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_decorations(self, page_count: int):
        self.saveState()
        case_id = getattr(self, "_case_id", "SAR")
        
        # Running Header (on pages > 1)
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(HexColor("#475569"))
            self.drawString(36, A4[1] - 25, "VigilOS // Suspicious Activity Report (SAR)")
            self.drawRightString(A4[0] - 36, A4[1] - 25, f"Case: {case_id}")
            self.setStrokeColor(HexColor("#CBD5E1"))
            self.setLineWidth(0.5)
            self.line(36, A4[1] - 29, A4[0] - 36, A4[1] - 29)

        # Running Footer (on all pages)
        self.setStrokeColor(HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, 40, A4[0] - 36, 40)
        
        self.setFont("Helvetica", 8)
        self.setFillColor(HexColor("#64748B"))
        self.drawString(36, 28, "Generated by VigilOS v1.0.0 — Confidential & Regulatory Sensitive")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 36, 28, page_text)
        self.restoreState()


# ── Formatting Helpers ────────────────────────────────────────────────────────

def _escape(text: Any) -> str:
    """Safely escape text for ReportLab XML/HTML-like Paragraphs."""
    if text is None:
        return "Not available"
    s = str(text)
    return saxutils.escape(s)


def _format_currency(val: Any) -> str:
    """Format numeric values as currency."""
    if val is None:
        return "Not available"
    try:
        f = float(val)
        return f"${f:,.2f}"
    except (ValueError, TypeError):
        return _escape(val)


def _format_datetime(val: Any) -> str:
    """Format ISO timestamp into clean UTC representation."""
    if not val:
        return "Not available"
    try:
        if isinstance(val, str):
            dt = datetime.fromisoformat(val.replace("Z", "+00:00"))
            return dt.strftime("%Y-%m-%d %H:%M:%S UTC")
        elif isinstance(val, datetime):
            return val.strftime("%Y-%m-%d %H:%M:%S UTC")
    except Exception:
        return str(val)
    return str(val)


def _get_risk_colors(level: str):
    """Return text color and background color for a risk level."""
    lvl = (level or "").upper()
    if lvl == "HIGH":
        return HIGH_RED, HIGH_RED_BG
    elif lvl == "MEDIUM":
        return MED_AMBER, MED_AMBER_BG
    elif lvl == "LOW":
        return LOW_GREEN, LOW_GREEN_BG
    return TEXT_MUTED, ROW_ALT_BG


def _get_action_colors(action: str):
    """Return text color and background color for recommendation actions."""
    act = (action or "").upper()
    if act == "BLOCK":
        return HIGH_RED, HIGH_RED_BG
    elif act == "ESCALATE":
        return MED_AMBER, MED_AMBER_BG
    elif act in ("MONITOR", "APPROVE"):
        return LOW_GREEN, LOW_GREEN_BG
    return TEXT_MUTED, ROW_ALT_BG


